def _span(les, n, pat):
    """从语料该行里现取一段（不手打）—— 引号内的括号是半角的，手打会写成全角。"""
    m = re.search(pat, _line(les, n))
    assert m, "span not found: %r @L%d:%d" % (pat, les, n)
    return "第 %d 课 `:%d`「%s」" % (les, n, m.group(0))

