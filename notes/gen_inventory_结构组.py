# check_linerefs() —— 行号越界自检（★★ 第十遍加的，起因见 §5.7 末）
#
# 为什么要有：@bram-9d29 把 `L89:187` 写错了 —— 而那一处**之所以能当场认出来，
# 只因为它越界了**（第 89 课一共 48 行，不存在 :187）。⇒ 我散文里那些手打的行号
