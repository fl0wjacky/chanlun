#   （@nova-8980 02:3x 口径「概念名本身不当引文收」的同一条：先定义什么算一条引文，再数。）
QUOTE_RE = re.compile(r"`:\d+(?:-\d+)?`「([^「」]+)」")
PROSE_QUOTE_RE = re.compile(r"「([^「」]+)」")

def hits(s):
    s = s.replace(BRK, "").strip()
    if len(s) < 8:
        return []
    return sorted(l for l, body in _corpus().items() if s in body)

def hitcell(texts):
    """返回 (最大命中课数, 跨课条目, 引文条数, 行文「」条数, <20 字引文条数)"""
    worst, multi, nq, nprose, nshort = 1, [], 0, 0, 0
    for t in texts:
        for m in QUOTE_RE.finditer(t):
            qq = m.group(1); h = hits(qq); nq += 1
            if len(qq) < 20:
                nshort += 1
            if len(h) > worst:
                worst = len(h)
            if len(h) > 1:
                # ★ 这里原来写「另见 第X课／第Y课」，而 h 里**含引文自己那一课** ⇒ 措辞误导，已改
                multi.append("命中 %d 课（%s）· 引句 %d 字「%s…」"
                             % (len(h), "／".join("第%d课" % x for x in h), len(qq), qq[:14]))
        nprose += len(PROSE_QUOTE_RE.findall(t)) - len(QUOTE_RE.findall(t))
    return worst, multi, nq, nprose, nshort

