def check_quotes(text):
    import re as _re
    def _norm(s):
        return _re.sub(r"\s+", "", s.replace("↵", "").replace("**", ""))
    corpus = "".join(_norm("".join(lines(n))) for n in range(1, 109))
    bad = []
    for blk in _re.findall(r"「([^」]+)」", text):
        if _norm(blk) in {_norm(a) for a in ALLOW}:
            continue
        miss = [fr for fr in _re.split(r"…+|\.\.\.+", _norm(blk)) if fr and fr not in corpus]
        if miss:
            bad.append((blk, miss))
    if bad:
        print("★★ 引文自检未过 —— 手打段落里有对不上语料的引文：", file=sys.stderr)
        for blk, miss in bad:
            print(f"  块：「{_norm(blk)[:60]}」", file=sys.stderr)
