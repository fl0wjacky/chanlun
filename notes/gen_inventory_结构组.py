# ─────────────── 引文（按标点切整句，跨行标 ↵） ───────────────

TERM_RE = re.compile(r"[。；！？]")   # 句末标点（**不含冒号**：冒号后面还有内容）
BRK = "↵"

def quote(lesson, n, needle=None, end=None, stop=None, skip=0, maxlines=4, raw=False):
    """返回 (行区间, 原文)。
    n      起始行
    needle 从 n 行起找这个子串当**引文起点**（用于引文起点在本行中间；可跨折行）
    end    直接取 n..end 行的原文，不切句
    stop   额外的截断标点（如「：」，用于只引到冒号为止）
    skip   跳过前 k 个句末标点再切（用于一句话里有多个句号的情形）
    raw    不切句，整行照抄（用于本副本里那句没有句末标点的情形）"""
    ls = lines(lesson)
    if end is not None or raw:
        e = end if end is not None else n
        span = ":%d" % n if e == n else ":%d-%d" % (n, e)
        return span, BRK.join(ls[k - 1].strip() for k in range(n, e + 1))
    chars = TERM_RE.pattern[1:-1] + (re.escape(stop) if stop else "")
    pat = re.compile("[%s]" % chars)
    parts, jo, s = [], "", 0
    for k in range(n, min(n + maxlines, len(ls) + 1)):
        parts.append(ls[k - 1].strip())
        jo = BRK.join(parts)
        if needle is not None:
            flat, up = [], []
            for i, ch in enumerate(jo):
                if ch != BRK:
                    flat.append(ch); up.append(i)
            fs = "".join(flat).find(needle)
            if fs < 0:
                continue                      # 还没拼到起点所在的折行，继续拼
            s = up[fs]
        h_ = list(pat.finditer(jo, s))
        if len(h_) > skip:
            cut = h_[skip].end()
            span_end = n + jo[:cut].count(BRK)
            span = ":%d" % n if span_end == n else ":%d-%d" % (n, span_end)
            return span, jo[s:cut]
    span_end = n + jo.count(BRK)
    span = ":%d" % n if span_end == n else ":%d-%d" % (n, span_end)
    return span, jo[s:]

def q(lesson, n, note="", **kw):
    span, txt = quote(lesson, n, **kw)
    return "第 %d 课 `%s`「%s」%s" % (lesson, span, txt, note)

