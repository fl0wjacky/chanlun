# 口径（★★ 第十遍第 2 版 —— 第 1 版虚报 4 条，改法写在下面，不改就是"狼来了"）：
#   · 课号**只认同一行内、明写的**「第 N 课」或 `LN`／`L N` 两种写法。
#     ★ 第 1 版还回看前 3 行找课号 —— **删掉了**：散文里常写「102 我点过名…84 我引过 `:57`」，
#       回看会抓到一个不相干的课号，于是把 84 的 `:57` 记成 102 的、虚报一条。
#     ⇒ **宁可漏检，不许虚报**：这条自检的价值全在"它一响就是真的"。
#   · **`:X` 前面一个字符不许是数字、冒号或字母** —— 为了排掉时间戳。
#     ★ 这也是实测逼出来的：源页标题有噪声时间戳 `... 22:228:31`，`:228` 被当成了行号引用。
#   · 行数用 `len(lines(n))`，与全表行号同一把尺（★ 不是 wc -l，见 §0）。
# ─────────────────────────────────────────────────────────────────────────────
def check_linerefs(text):
    import re as _re
    # ★ 第十一遍修：课号标记必须按**位置**取最后一个，不能把两种写法分别 findall 再拼接 ——
    #   那等于让所有 `L\d` 无脑压过所有 `第N课`（2026-10-01 假红：正文里一句『我核 L91 时』，
    #   就把同一行后面明明写着「第 65 课 :145」的引用判成 L91 越界）。
    # ★★ 再修一处【静默错归】：原文里也常写「77 课」（不带『第』）—— 旧正则看不见它，
    #   于是这个 `:ref` 会**回落到本行更早的那个课号**上。若不越界就**悄悄通过**（错归但不报），
    #   越界才暴露（2026-10-01：`与 77 课 \`:66\`–\`:70\`` 被归给前面那句『第 69 课』⇒ 假越界）。
    #   ⇒ 补上第三式 `(\d{1,3})\s*课`，把这类静默错归一并收掉。
    _MARK = _re.compile(r"第\s*(\d{1,3})\s*课|\bL\s*(\d{1,3})\b|(\d{1,3})\s*课")
    _REF = _re.compile(r"(^|[^\d:A-Za-z]):(\d{1,4})")
    _len = {n: len(lines(n)) for n in range(1, 109)}
    bad, checked = [], 0
    tl = text.split("\n")
    for i, line in enumerate(tl):
        for m in _REF.finditer(line):
            x = int(m.group(2))
            cur = [int(a or b or c) for a, b, c in _MARK.findall(line[:m.start()])]
            cand = [c for c in cur if 1 <= c <= 108]
            if not cand:
                continue
            n = cand[-1]
            checked += 1
            if x > _len[n]:
                bad.append((i + 1, n, x, _len[n], line.strip()[:70]))
    if bad:
        print("★★ 行号越界 —— 引的课没有这么多行（@bram-9d29 那个 L89:187 就是这一类）：", file=sys.stderr)
        for ln, n, x, mx, s in bad:
            print(f"  输出第 {ln} 行：说「第 {n} 课 :{x}」，但第 {n} 课只有 {mx} 行", file=sys.stderr)
            print(f"      …{s}", file=sys.stderr)
        print("  ⇒ 改行号，或把课号写清楚。", file=sys.stderr)
        sys.exit(1)
    return checked


