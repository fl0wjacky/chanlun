def locate(n, q, dup=False):
    m = MG[n]
    i = m.find(q)
    assert i >= 0, ("未命中：L%d %s %s" % (n, q[:44], _diagnose(n, q)))
    if m.find(q, i + 1) >= 0:
        if not dup:
            raise AssertionError("非唯一：L%d %s" % (n, q[:44]))
        DUP.append((n, q[:30]))
    pos = 0
    out = []
    hit = []
    for k, ln in enumerate(NL[n], 1):
        s = pos
        pos += len(ln)
        if i < pos and i + len(q) > s:
            hit.append(k)
        for j in range(max(i, s), min(i + len(q), pos)):
            out.append(ln[j - s])
            if j + 1 == pos:
                out.append("↵")
    return (hit[0], hit[-1]), "".join(out).rstrip("↵")


def Q(n, q, dup=False):
    rng, q2 = locate(n, q, dup)
    tag = ("`L%d:%d`" % (n, rng[0])) if rng[0] == rng[-1] else ("`L%d:%d-%d`" % (n, rng[0], rng[-1]))
    return "%s「%s」" % (tag, q2)


def QL(n, a, b=None, dup=False):
    """★ 引文按**行号**取（1-based，含端点）：语料里怎么断行就怎么拼，一个字都不经我手。

    两侧都断言：① 取出的串必须落回**同样的行号**（落偏了说明这段文字在别处也出现）。
    """
    b = a if b is None else b
    q = "".join(NL[n][a - 1:b])
    rng, q2 = locate(n, q, dup)
    assert rng == (a, b), "QL 行号对不上：要 L%d:%d-%d，实际落在 %s" % (n, a, b, rng)
    tag = ("`L%d:%d`" % (n, a)) if a == b else ("`L%d:%d-%d`" % (n, a, b))
    return "%s「%s」" % (tag, q2)


def QS(n, i, sub, dup=False):
    """★ 引文是**某一行里的一小段**：先断言它确实在这一行，再交给 Q() 定位。

    这一手专治『抄串行』—— 段落搬家时行号会错，而行号错在 Q() 里是**看不见**的
    （只要那段文字在别处也能命中，行号就会指到别处去）。

    ★ 小段可能在全课出现**多次**（`L30:17` 与 `L30:28` 就有同一句）。此时：
      · 必须指定 `dup=True`（Q() 才肯放行）；
      · 且**首个命中必须在第 i 行** —— 否则 Q() 印出来的行号会指到别处去，
        这时该做的是**把引文加长到唯一**，不是加 dup。
    """
    assert sub in NL[n][i - 1], "QS 与行不符：L%d:%d 里没有 %r" % (n, i, sub)
    m, starts, j = MG[n], [], MG[n].find(sub)
    while j >= 0:
        starts.append(j)
        j = m.find(sub, j + 1)
    bounds, off = [], 0
    for ln in NL[n]:
        bounds.append((off, off + len(ln)))
        off += len(ln)
    where = lambda pos: next(k for k, (s, e) in enumerate(bounds, 1) if s <= pos < e)
    lines = [where(s) for s in starts]
    assert lines[0] == i, "QS 首个命中在 L%d:%d、不是 L%d:%d —— 引文要加长到唯一" % (n, lines[0], n, i)
    return Q(n, sub, dup=dup)


