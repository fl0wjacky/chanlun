def main():
    dry = "--dry" in sys.argv
    corpus = "".join(open(f, encoding="utf-8").read().replace("\r", "").replace("\n", "")
                     for f in sorted(glob.glob(os.path.join(ROOT, "archive/chanlun108/text/lesson-*.txt"))))
    assert corpus, "语料没加载到 —— 先确认 archive/ 就位。"
    t = open(P, encoding="utf-8").read()
    n = 0
    for old, new, why in REPL:
        assert new.replace("↵", "") in corpus, \
            "新块在语料里找不到（会被 checkquotes 判不中）：%s" % new[:40]
        assert new.startswith(old), "新块不是旧块的延长（本脚本只做加法）：%s" % old[:30]
        # ★ 匹配按**块尾**（`old」`），不是整块 —— 有些缺陷是长块的**尾巴**被掐掉
        #   （如「…但站在」），整块匹配找不到它。old 是 new 的前缀 ⇒ 替完不再自匹配 ⇒ 幂等。
        c_old, c_new = t.count(old + "」"), t.count(new + "」")
        if c_old == 0:
            print("· 已是修后状态（%d 处）：%s" % (c_new, old[-30:]))
            continue
        assert c_old >= 1, "找不到旧块：%s" % old[:40]
        t = t.replace(old + "」", new + "」")
        n += c_old
        print("✓ %d 处 +%d 字：%s…（%s）" % (c_old, len(new) - len(old), old[:26], why.split("——")[0].strip()))
    if dry:
        print("--dry：未写盘。共会改 %d 处。" % n)
        return 0
    if n:
        open(P, "w", encoding="utf-8").write(t)
        print("已写盘：%d 处。跑 checkquotes.py --min 4 —— 逐字读数必须一字不变。" % n)
    else:
        print("无需改动。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
