def OCC(n, sub):
    """这串在合并文本里**出现几次、各落在哪一行** —— 给『同一串反复出现』这类缺陷断言用。

    ★ 为什么需要它：QS() 要求**首个命中就在指定行**，所以它天生表达不了『它在第 56 行又出现一次』。
      缺陷那一栏恰恰全是这种句子 ⇒ 不许用散文写，得能当场算出来。
    """
    m, starts, j = MG[n], [], MG[n].find(sub)
    while j >= 0:
        starts.append(j)
        j = m.find(sub, j + 1)
    bounds, off = [], 0
