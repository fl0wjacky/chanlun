def QL(n, a, b=None, dup=False):
    """引文按**行号**取（1-based，含端点），并断言取出的串必须落回**同样的行号**。"""
    b = a if b is None else b
    q = "".join(NL[n][a - 1:b])
    rng, q2 = locate(n, q, dup)
    assert rng == (a, b), "QL 行号对不上：要 L%d:%d-%d，实际落在 %s" % (n, a, b, rng)
    tag = ("`L%d:%d`" % (n, a)) if a == b else ("`L%d:%d-%d`" % (n, a, b))
    return "%s「%s」" % (tag, q2)


def QS(n, i, sub, dup=False):
    """引文是**某一行里的一小段**：先断言它确实在这一行，且 Q() 的首个命中也在这一行。"""
    assert sub in NL[n][i - 1], "QS 与行不符：L%d:%d 里没有 %r" % (n, i, sub)
    m, starts, j = MG[n], [], MG[n].find(sub)
    while j >= 0:
        starts.append(j)
        j = m.find(sub, j + 1)
    bounds, off = [], 0
    for ln in NL[n]:
        bounds.append((off, off + len(ln)))
        off += len(ln)
    where = lambda pos: next(k for k, (s, e) in enumerate(bounds, 1) if s <= pos < e)
    lines = [where(s) for s in starts]
    assert lines[0] == i, "QS 首个命中在 L%d:%d、不是 L%d:%d —— 引文要加长到唯一" % (n, lines[0], n, i)
    return Q(n, sub, dup=dup)


