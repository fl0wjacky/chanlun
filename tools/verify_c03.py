#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""验证 c03 卡片上画的四组数据：引擎算出来的分型/笔，是否和卡片标称的一致。"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from core import standardize, fractals, build_pens, check_standardized

# 与 cards/c03_pen.py 中完全相同的画图数据 (o,h,l,c)
A = [(100.5,101.0,99.5,99.8), (99.8,100.0,98.6,99.0), (99.0,99.2,97.8,98.4),
     (98.4,100.2,98.4,99.6),  (99.6,101.4,99.6,100.8), (100.8,102.2,100.4,101.6),
     (101.6,103.0,101.2,101.8), (101.8,102.4,100.6,101.0), (101.0,101.6,99.8,100.2)]
P1 = [(100.0,100.2,98.8,99.2), (99.2,99.4,97.8,98.6), (98.6,100.0,98.4,99.6),
      (99.6,101.2,99.4,100.8), (100.8,102.2,100.4,101.8), (101.8,103.0,101.4,102.0),
      (102.0,102.4,100.8,101.4)]
P2 = [(100.5,102.5,100.0,102.0), (102.0,103.0,101.0,101.5), (101.5,102.0,100.0,100.5),
      (100.5,101.0,99.0,99.5), (99.5,100.0,98.0,98.5), (98.5,98.8,97.0,97.5),
      (97.5,99.2,97.2,98.6)]
P4 = [(99.0,100.0,98.5,100.0), (100.0,102.5,100.0,101.0), (100.5,101.0,99.0,100.0),
      (100.8,102.0,100.0,101.5), (101.8,103.5,101.5,103.0), (103.0,104.5,102.5,103.2),
      (103.4,103.8,102.0,102.6)]

CASE = [("A 解剖图", A, "底@2 + 顶@6 → 1 笔"),
        ("① 向上笔", P1, "底@1 + 顶@5 → 1 笔（向上）"),
        ("② 向下笔", P2, "顶@1 + 底@5 → 1 笔（向下）"),
        ("③④ 同一段行情", P4, "顶@1 + 底@2(间隔1，跳过) + 顶@5(同类，顶替顶@1) → 0 笔，端点=顶@5")]

fail = 0
for name, raw, expect in CASE:
    bars = [{"h": x[1], "l": x[2]} for x in raw]
    std = standardize(bars)
    fx = fractals(std)
    pens, seq = build_pens(fx, 4)
    bad = check_standardized(std)
    fxtxt = " ".join(("顶" if f["type"] == "top" else "底") + str(f["k"]) for f in fx)
    print("=" * 62)
    print("%s   标称：%s" % (name, expect))
    print("   原始 %d 根 → 标准化 %d 根（无包含：%s）" % (len(bars), len(std), not bad))
    print("   分型：", fxtxt if fxtxt else "（无）")
    print("   笔端点：", " ".join(("顶" if f["type"] == "top" else "底") + str(f["k"]) for f in seq))
    print("   笔数： %d" % len(pens))
    fail += len(bad)
print("=" * 62)
print("四组数据全部无包含违规" if fail == 0 else "有 %d 处包含违规！" % fail)
